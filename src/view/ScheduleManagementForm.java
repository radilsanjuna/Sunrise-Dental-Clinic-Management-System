    // Setup year, month and day combo boxes
    private void setupDate() {

        cmbYear.removeAllItems();
        cmbYear.addItem("Year");

        int currentYear = LocalDate.now().getYear();

        for (int i = currentYear; i <= currentYear + 2; i++) {
            cmbYear.addItem(String.valueOf(i));
        }

        cmbMonth.removeAllItems();
        cmbMonth.addItem("Month");

        String[] months = {
            "01 - January",
            "02 - February",
            "03 - March",
            "04 - April",
            "05 - May",
            "06 - June",
            "07 - July",
            "08 - August",
            "09 - September",
            "10 - October",
            "11 - November",
            "12 - December"
        };

        for (String month : months) {
            cmbMonth.addItem(month);
        }

        cmbDay.removeAllItems();
        cmbDay.addItem("Day");
    }

    // Load all schedules into the table
private void loadSchedules() {

    DefaultTableModel model =
            (DefaultTableModel) tblSchedule.getModel();

    model.setRowCount(0);

    List<DentistSchedule> schedules =
            scheduleController.getAllSchedules();

    if (schedules == null) {
        return;
    }

    for (DentistSchedule schedule : schedules) {

        model.addRow(new Object[]{
            schedule.getScheduleId(),
            schedule.getDentistName(),
            schedule.getScheduleDate(),
            schedule.getStartTime(),
            schedule.getEndTime()
        });
    }
}
    // Clear all input fields
    private void clearFields() {

        txtScheduleId.setText("");

        cmbDentist.setSelectedIndex(0);
        cmbYear.setSelectedIndex(0);
        cmbMonth.setSelectedIndex(0);

        cmbDay.removeAllItems();
        cmbDay.addItem("Day");

        cmbStartTime.setSelectedIndex(0);
        cmbEndTime.setSelectedIndex(0);

        tblSchedule.clearSelection();
    }

    // Load dentists into the combo box
private void loadDentists() {

    cmbDentist.removeAllItems();

    cmbDentist.addItem("Select Dentist");

    dentistList =
            dentistController.getAllDentists();

    if (dentistList == null) {
        return;
    }

    for (Dentist dentist : dentistList) {

        cmbDentist.addItem(
                dentist.getFullName()
        );
    }
}

    // Get the selected dentist ID
    private int getSelectedDentistId() {

        int index =
                cmbDentist.getSelectedIndex();

        if (index <= 0 || dentistList == null) {
            return -1;
        }

        if (index - 1 >= dentistList.size()) {
            return -1;
        }

        return dentistList
                .get(index - 1)
                .getDentistId();
    }

    // Get the selected date
    private LocalDate getSelectedDate() {

        if (cmbYear.getSelectedIndex() == 0
                || cmbMonth.getSelectedIndex() == 0
                || cmbDay.getSelectedIndex() == 0) {

            return null;
        }

        try {

            int year =
                    Integer.parseInt(
                            cmbYear.getSelectedItem().toString()
                    );

            int month =
                    cmbMonth.getSelectedIndex();

            int day =
                    Integer.parseInt(
                            cmbDay.getSelectedItem().toString()
                    );

            return LocalDate.of(
                    year,
                    month,
                    day
            );

        } catch (Exception e) {

            return null;
        }
    }








