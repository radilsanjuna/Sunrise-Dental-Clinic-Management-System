    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
    
     if (txtScheduleId.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter a Schedule ID."
            );

            return;
        }

        int scheduleId;

        try {

            scheduleId =
                    Integer.parseInt(
                            txtScheduleId.getText().trim()
                    );

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Schedule ID must be a number."
            );

            return;
        }

        DentistSchedule schedule =
                scheduleController.searchSchedule(scheduleId);

        if (schedule == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Schedule not found."
            );

            return;
        }

        LocalDate date =
                schedule.getScheduleDate();

        cmbYear.setSelectedItem(
                String.valueOf(date.getYear())
        );

        cmbMonth.setSelectedIndex(
                date.getMonthValue()
        );

        cmbDay.setSelectedItem(
                String.format(
                        "%02d",
                        date.getDayOfMonth()
                )
        );

        cmbStartTime.setSelectedItem(
                schedule.getStartTime()
                        .format(
                                DateTimeFormatter.ofPattern("hh:mm a")
                        )
        );

        cmbEndTime.setSelectedItem(
                schedule.getEndTime()
                        .format(
                                DateTimeFormatter.ofPattern("hh:mm a")
                        )
        );

        if (dentistList != null) {

            for (int i = 0;
                    i < dentistList.size();
                    i++) {

                if (dentistList
                        .get(i)
                        .getDentistId()
                        == schedule.getDentistId()) {

                    cmbDentist.setSelectedIndex(i + 1);
                    break;
                }
            }
        }
    }//GEN-LAST:event_btnSearchActionPerformed

