private void loadDentistUsers() {

    cmbDentistUser.removeAllItems();
    cmbDentistUser.addItem("Select Dentist User");

    try {

        List<User> userList =
                userController.getDentistUsers();

        for (User user : userList) {

            String displayText =
                    user.getUserId()
                    + " - "
                    + user.getFullName()
                    + " ("
                    + user.getUsername()
                    + ")";

            cmbDentistUser.addItem(displayText);
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error loading dentist users: "
                        + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}
    
    
private void clearFields() {

    txtDentistId.setText("");

    cmbDentistUser.setSelectedIndex(0);

    cmbSpecialization.setSelectedIndex(0);

    txtPhoneNumber.setText("");
}


 private void loadDentistsToTable() {

    DefaultTableModel tableModel =
            (DefaultTableModel) tblDentist.getModel();

    tableModel.setRowCount(0);

    try {

        List<Dentist> dentistList =
                dentistController.getAllDentists();

        for (Dentist dentist : dentistList) {

            Object[] rowData = {

                dentist.getDentistId(),
                dentist.getUserId(),
                dentist.getFullName(),
                dentist.getSpecialization(),
                dentist.getPhoneNumber()
            };

            tableModel.addRow(rowData);
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error loading dentists: "
                        + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

