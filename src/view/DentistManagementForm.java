    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed

   String selectedUser =
            cmbDentistUser.getSelectedItem().toString();

    String specialization =
            cmbSpecialization.getSelectedItem().toString();

    String phoneNumber =
            txtPhoneNumber.getText().trim();

    if (selectedUser.equals("Select Dentist User")) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a Dentist User."
        );

        return;
    }

    if (specialization.equals("Select Specialization")) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a specialization."
        );

        return;
    }

    if (phoneNumber.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter the phone number."
        );

        return;
    }

    if (!phoneNumber.matches("^0\\d{9}$")) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter a valid 10-digit phone number."
        );

        return;
    }

    try {

        int userId =
                Integer.parseInt(
                        selectedUser.split(" - ")[0]
                );

        Dentist dentist =
                new Dentist(
                        0,
                        userId,
                        null,
                        specialization,
                        phoneNumber
                );

        boolean added =
                dentistController.addDentist(dentist);

        if (added) {

            JOptionPane.showMessageDialog(
                    this,
                    "Dentist added successfully!"
            );

            clearFields();
            loadDentistsToTable();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to add dentist. "
                    + "This user may already have a dentist profile."
            );
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Invalid User ID."
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
        );
    }
    
    }//GEN-LAST:event_btnAddActionPerformed

    
    
    
    
    
    
    
    
    
    
    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed

           String idText =
            txtDentistId.getText().trim();

    if (idText.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter a Dentist ID."
        );

        return;
    }

    try {

        int dentistId =
                Integer.parseInt(idText);

        Dentist dentist =
                dentistController.searchDentist(dentistId);

        if (dentist == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Dentist not found."
            );

            return;
        }

        selectDentistUser(dentist.getUserId());

        cmbSpecialization.setSelectedItem(
                dentist.getSpecialization()
        );

        txtPhoneNumber.setText(
                dentist.getPhoneNumber()
        );

        JOptionPane.showMessageDialog(
                this,
                "Dentist found successfully."
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Dentist ID must be a valid number."
        );
    }
    }//GEN-LAST:event_btnSearchActionPerformed

    
    


    
private void selectDentistUser(int userId) {

    for (int i = 0;
         i < cmbDentistUser.getItemCount();
         i++) {

        String item =
                cmbDentistUser.getItemAt(i);

        if (item.startsWith(userId + " - ")) {

            cmbDentistUser.setSelectedIndex(i);

            return;
        }
    }
}
     
  


    
    
